    WINDOW_RADIUS = 'WINDOW_RADIUS'
    INTERNAL_WINDOW_RADIUS = 'INTERNAL_WINDOW_RADIUS'
    LOW_MEMORY = 'LOW_MEMORY'
    OUTPUT_FOLDER = 'OUTPUT_FOLDER'
